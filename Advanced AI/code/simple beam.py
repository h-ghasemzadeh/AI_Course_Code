# محاسبه خیز وسط تیر دوسر ساده تحت بار متمرکز در وسط

def beam_deflection(load_ton):
    # -----------------------------
    # ثابت ها
    L = 5  # طول تیر (متر)
    E = 2.1e11  # مدول الاستیسیته فولاد (پاسکال)
    I = 1.64e-5  # ممان اینرسی IPE 180 (m^4)
    g = 9.81  # شتاب گرانش (m/s^2)
    # -----------------------------
    
    # تبدیل تن به نیوتن
    P = load_ton * 1000 * g  # تن → کیلوگرم → نیوتن
    
    # فرمول خیز
    delta = (P * L**3) / (48 * E * I)
    
    # تبدیل به میلیمتر
    delta_mm = delta * 1000
    
    return delta_mm


# دریافت ورودی از کاربر
load = float(input("بار متمرکز در وسط تیر را بر حسب تن وارد کنید: "))
deflection = beam_deflection(load)

print(f"\nخیز وسط تیر برابر است با: {deflection:.3f} میلیمتر")