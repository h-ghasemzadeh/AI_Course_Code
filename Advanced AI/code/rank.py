# تعریف ماتریس X بر اساس تصویر جدید ارائه شده
import numpy as np
X = np.array([
    [210.4, 5, 1, 45, 2104],
    [141.6, 3, 2, 40, 1416],
    [153.4, 3, 2, 30, 1534],
    [85.2, 2, 1, 36, 852],
    [300, 4, 1, 38, 3000],
    [280, 5, 3, 20, 2800]
])

# محاسبه رنک ماتریس X
rank = np.linalg.matrix_rank(X)
print(rank)